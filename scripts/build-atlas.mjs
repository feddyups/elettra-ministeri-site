/**
 * Generates the data behind the color infographic blocks (src/color/):
 *   src/color/atlas.generated.js   every work's palette, every series' fingerprint, and the overall signature
 *
 * It reads the catalogue's high-resolution images, so it needs the catalogue folder:
 *   npm run build:atlas -- --catalogue "/path/to/catalogue"
 * To add a work, add it to scripts/palette/works.config.mjs and run this again.
 */
import { writeFileSync } from 'node:fs';
import { runAnalysis } from './palette/run.mjs';
import { SERIES } from '../src/themes/tones.config.js';
import { TONES } from '../src/themes/tones.generated.js';
import { rgbToOklab, oklabToRgb, toHex, chroma, hue } from './palette/color-science.mjs';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
};

const pct = (v) => Math.round(v * 100);
const colors = (palette) => palette.map((c) => [c.hex, c.name, +c.share.toFixed(3)]);
const pageOf = (slug) => SERIES[slug].path || `/paintings/${slug}`;

/**
 * The series' accent for rings and highlights: its site tone (the color of its home section and page),
 * lightened so it reads on a dark ground. Changing a series color in tones.config.js changes this too.
 */
const accentOf = (slug) => {
  const rgb = TONES[slug].bg.match(/\d+/g).slice(0, 3).map(Number);
  const lab = rgbToOklab(...rgb);
  const C = Math.min(Math.max(chroma(lab), 0.09), 0.15);
  const h = hue(lab) * Math.PI / 180;
  return toHex(oklabToRgb([0.74, C * Math.cos(h), C * Math.sin(h)]));
};

const report = await runAnalysis({ catalogueDir: arg('catalogue', process.env.CATALOGUE_DIR), k: 5 });

const fingerprint = (s) => ({
  warm: pct(s.warm), green: pct(s.green), cool: pct(s.cool), violet: pct(s.violet), vivid: pct(s.vibrancy),
  chroma: +s.meanChroma.toFixed(3), light: +s.meanLightness.toFixed(3), hue: s.hueBins,
});

const atlas = {
  overall: {
    works: report.overall.works,
    ...fingerprint(report.overall),
    palette: colors(report.overall.signature),
    loud: colors(report.overall.accents),
    pair: report.overall.complementary && {
      a: [report.overall.complementary.a.hex, report.overall.complementary.a.name],
      b: [report.overall.complementary.b.hex, report.overall.complementary.b.name],
    },
  },
  series: Object.fromEntries(Object.entries(report.series).map(([slug, s]) => [slug, {
    label: SERIES[slug].label,
    path: pageOf(slug),
    works: s.works,
    accent: accentOf(slug),
    ...fingerprint(s),
    palette: colors(s.palette),
  }])),
  works: report.works.map((w) => ({
    id: w.id,
    title: w.title,
    series: w.series,
    href: `${pageOf(w.series)}#${w.anchor}`,
    ...fingerprint({ ...w.stats, hueBins: [] }),
    palette: colors(w.palette),
  })).map(({ hue, ...rest }) => rest),
};

const body = JSON.stringify(atlas);
writeFileSync(
  new URL('../src/color/atlas.generated.js', import.meta.url),
  `/* Generated by scripts/build-atlas.mjs from scripts/palette/works.config.mjs. Do not edit; change the config and run \`npm run build:atlas\`. */\nexport const ATLAS = ${body};\n`,
);
console.log(`Wrote src/color/atlas.generated.js: ${atlas.works.length} works in ${Object.keys(atlas.series).length} series`);

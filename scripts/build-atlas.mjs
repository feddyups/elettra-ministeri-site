/**
 * Generates the data behind the color infographic blocks (src/color/):
 *   src/color/atlas.generated.js   every work's palette, every series' fingerprint, and the overall signature
 *   src/themes/series-attr.js      the pre-paint script that tags a page with its series (needs to know each painting's series)
 *
 * It reads the catalogue's high-resolution images, so it needs the catalogue folder:
 *   npm run build:atlas -- --catalogue "/path/to/catalogue"
 * To add a work, add it to scripts/palette/works.config.mjs and run this again.
 */
import { writeFileSync } from 'node:fs';
import { runAnalysis } from './palette/run.mjs';
import { SERIES } from '../src/themes/tones.config.js';
import { CATALOGUE } from '../src/works/catalogue.js';
import { CARDS } from '../src/print/cards.js';
import { TONES, PRESET_IDS, DEFAULT_PRESET } from '../src/themes/tones.generated.js';
import { rgbToOklab, oklabToRgb, toHex, chroma, hue } from './palette/color-science.mjs';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
};

const pct = (v) => Math.round(v * 100);
const colors = (palette) => palette.map((c) => [c.hex, c.name, +c.share.toFixed(3)]);
const pageOf = (slug) => SERIES[slug].path || `/paintings/${slug}`;

/**
 * The series' accent for rings and highlights: its site tone (the color of its home section and page),
 * lightened so it reads on a dark ground. Changing a series color in tones.config.js changes this too.
 */
const accentOf = (slug) => {
  const rgb = TONES[slug].bg.match(/\d+/g).slice(0, 3).map(Number);
  const lab = rgbToOklab(...rgb);
  const C = Math.min(Math.max(chroma(lab), 0.09), 0.15);
  const h = hue(lab) * Math.PI / 180;
  return toHex(oklabToRgb([0.74, C * Math.cos(h), C * Math.sin(h)]));
};

const report = await runAnalysis({ catalogueDir: arg('catalogue', process.env.CATALOGUE_DIR), k: 5 });

const fingerprint = (s) => ({
  warm: pct(s.warm), green: pct(s.green), cool: pct(s.cool), violet: pct(s.violet), vivid: pct(s.vibrancy),
  chroma: +s.meanChroma.toFixed(3), light: +s.meanLightness.toFixed(3), hue: s.hueBins, cast: s.cast,
});

const atlas = {
  overall: {
    works: report.overall.works,
    ...fingerprint(report.overall),
    palette: colors(report.overall.signature),
    loud: colors(report.overall.accents),
    pair: report.overall.complementary && {
      a: [report.overall.complementary.a.hex, report.overall.complementary.a.name],
      b: [report.overall.complementary.b.hex, report.overall.complementary.b.name],
    },
  },
  series: Object.fromEntries(Object.entries(report.series).map(([slug, s]) => [slug, {
    label: SERIES[slug].label,
    path: pageOf(slug),
    works: s.works,
    accent: accentOf(slug),
    ...fingerprint(s),
    palette: colors(s.palette),
  }])),
  works: report.works.map((w) => ({
    id: w.id,
    title: w.title,
    series: w.series,
    slug: w.anchor,
    href: CATALOGUE[w.anchor] ? `${CATALOGUE[w.anchor].series === 'textiles' ? '/textiles' : '/paintings'}/${w.anchor}` : `${pageOf(w.series)}#${w.anchor}`,
    ...fingerprint({ ...w.stats, hueBins: [] }),
    palette: colors(w.palette),
  })).map(({ hue, ...rest }) => rest),
};

const body = JSON.stringify(atlas);
writeFileSync(
  new URL('../src/color/atlas.generated.js', import.meta.url),
  `/* Generated by scripts/build-atlas.mjs from scripts/palette/works.config.mjs. Do not edit; change the config and run \`npm run build:atlas\`. */\nexport const ATLAS = ${body};\n`,
);
console.log(`Wrote src/color/atlas.generated.js: ${atlas.works.length} works in ${Object.keys(atlas.series).length} series`);

const workSeries = { ...Object.fromEntries(Object.entries(CATALOGUE).map(([slug, work]) => [slug, work.series])), ...Object.fromEntries(CARDS.map((card) => [card.slug, 'print'])) };
writeFileSync(
  new URL('../src/themes/series-attr.js', import.meta.url),
  `/* Generated by scripts/build-atlas.mjs. Do not edit; change src/works/catalogue.js and run \`npm run build:atlas\`. */
/*
 * Marks the Print page (/print) as data-series="print", the page of every painting (/paintings) as data-series="all", and a series page (/paintings/<series>), a painting page (/paintings/<painting>, or /textiles/<textile>) or the /textiles page with
 * data-series="<series>" before the page is first painted, so series-theme.css and tones.generated.css can color it
 * without a flash of the default colors. A classic script on purpose: it has to run before the first paint, and it imports nothing.
 */
(function () {
  var paintingSeries = ${JSON.stringify(workSeries)};
  var path = location.pathname.replace(/\\/$/, '');
  var match = path.match(/^\\/(?:paintings|textiles|print)\\/([a-z0-9-]+)$/);
  var series = match ? (paintingSeries[match[1]] || match[1]) : path === '/textiles' ? 'textiles' : path === '/print' ? 'print' : path === '/paintings' ? 'all' : null;
  if (series) document.documentElement.setAttribute('data-series', series);
  // the background the visitor chose for this series (theme/tone-control.js keeps the preset's name in localStorage), before the first paint
  try {
    var tone = series && localStorage.getItem('em-tone-' + series);
    if (tone && tone !== '${DEFAULT_PRESET}' && ${JSON.stringify(PRESET_IDS)}.indexOf(tone) > -1) document.documentElement.setAttribute('data-tone', tone);
  } catch (e) { /* storage blocked: the default preset shows */ }
  // a textile reached through its old /paintings address shows its own /textiles address
  if (match && (series === 'textiles' || series === 'print') && path.indexOf('/paintings/') === 0) history.replaceState(history.state, '', '/' + series + '/' + match[1] + location.search + location.hash);
})();
`,
);

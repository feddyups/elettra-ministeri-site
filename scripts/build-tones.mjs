/**
 * Generates the site's color map from src/themes/tones.config.js:
 *   src/themes/tones.generated.js   the tones as a JS module (home page sections)
 *   src/themes/tones.generated.css  the same tones as CSS variables (series pages, no flash of the wrong color)
 *
 * Usage: npm run build:tones (after `npm run build:atlas`, which supplies the series palettes)
 */
import { writeFileSync } from 'node:fs';
import { rgbToOklab, oklabToRgb } from '../src/lib/color-science.js';
import { SERIES, TONE_SETTINGS, TONE_PRESETS, DEFAULT_TONE, CHOSEN_TONES, NIGHT_TONE } from '../src/themes/tones.config.js';
import { ATLAS } from '../src/color/atlas.generated.js';
import { deriveGrounds, contrastOf } from './palette/series-ground.mjs';

const OUT = new URL('../src/themes/', import.meta.url);

const parseColor = (value) => {
  const hex = value.trim().replace('#', '');
  if (/^[0-9a-f]{6}$/i.test(hex)) return [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
  const rgb = value.match(/\d+(\.\d+)?/g);
  if (rgb && rgb.length >= 3) return rgb.slice(0, 3).map(Number);
  throw new Error(`Cannot read the color "${value}"`);
};

const rgbString = (c) => `rgb(${c.map((v) => Math.round(v)).join(',')})`;
const alpha = (c, a) => `rgba(${c.map((v) => Math.round(v)).join(',')},${a})`;
const hueOf = (c) => Math.round((Math.atan2(...rgbToOklab(...c.map(Math.round)).slice(1).reverse()) * 180 / Math.PI + 360) % 360);

/** The series color's deeper sibling: same hue, lightness scaled by TONE_SETTINGS.altDepth. */
const deeper = (color) => {
  const [L, a, b] = rgbToOklab(...color.map(Math.round));
  return oklabToRgb([L * TONE_SETTINGS.altDepth, a * 0.92, b * 0.92]);
};

const ink = parseColor(TONE_SETTINGS.ink);
const settings = { ...TONE_SETTINGS.ground, ink };

// the grounds come from the cast of the colors of each series and of the whole body of work in the color analysis (run `npm run build:atlas` first when the works change)
const groups = Object.fromEntries(Object.keys(SERIES).filter((slug) => !SERIES[slug].bg).map((slug) => [slug, { cast: ATLAS.series[slug].cast, meanChroma: ATLAS.series[slug].chroma }]));
groups.all = { cast: ATLAS.overall.cast, meanChroma: ATLAS.overall.chroma };
const derived = deriveGrounds(groups, settings);
const opposite = deriveGrounds(groups, settings, 180);

/** A preset's tone: its background and the deeper second tone beside it. The text must read on both. */
const MIN_READABLE = 7;
const toneOf = (slug, preset, color, alt = deeper(color)) => {
  for (const [name, c] of [['background', color], ['second tone', alt]]) {
    if (contrastOf(c, ink) < MIN_READABLE) throw new Error(`${slug} / ${preset}: the text does not read on the ${name} ${rgbString(c)} (${contrastOf(c, ink).toFixed(1)}:1, at least ${MIN_READABLE}:1 needed)`);
  }
  return { bg: rgbString(color), alt: rgbString(alt), fg: TONE_SETTINGS.ink };
};

const slugs = [...Object.keys(SERIES), 'all'];
const presets = {};
for (const slug of slugs) {
  const pinned = SERIES[slug] && SERIES[slug].bg;
  const tonal = pinned ? parseColor(SERIES[slug].bg) : derived[slug].rgb;
  presets[slug] = {
    chosen: toneOf(slug, 'chosen', CHOSEN_TONES[slug] ? parseColor(CHOSEN_TONES[slug]) : tonal),
    tonal: toneOf(slug, 'tonal', tonal),
    contrast: toneOf(slug, 'contrast', pinned ? tonal : opposite[slug].rgb),
    night: toneOf(slug, 'night', parseColor(NIGHT_TONE.bg), parseColor(NIGHT_TONE.alt)),
  };
  const how = pinned ? 'pinned by hand' : derived[slug].why;
  console.log(`${slug.padEnd(14)} default ${DEFAULT_TONE}: ${presets[slug][DEFAULT_TONE].bg} (hue ${hueOf(parseColor(presets[slug][DEFAULT_TONE].bg))})`);
  console.log(`${''.padEnd(14)} ${TONE_PRESETS.filter((t) => t.id !== DEFAULT_TONE).map((t) => `${t.id} ${presets[slug][t.id].bg}`).join('  ')}   [tonal: ${how}]`);
}

const banner = 'Generated by scripts/build-tones.mjs from tones.config.js. Do not edit; change the config and run `npm run build:tones`.';

const js = `/* ${banner} */
/** The backgrounds a visitor can choose between for each series and for the page of all paintings, and the one every page shows until they choose. */
export const PRESET_IDS = ${JSON.stringify(TONE_PRESETS.map((t) => t.id))};
export const DEFAULT_PRESET = '${DEFAULT_TONE}';
export const PRESET_INFO = ${JSON.stringify(Object.fromEntries(TONE_PRESETS.map((t) => [t.id, { label: t.label, note: t.note }])), null, 2)};
export const PRESETS = {
${slugs.map((slug) => `  '${slug}': {\n${TONE_PRESETS.map((t) => `    ${t.id}: { bg: '${presets[slug][t.id].bg}', alt: '${presets[slug][t.id].alt}', fg: '${TONE_SETTINGS.ink}' },`).join('\n')}\n  },`).join('\n')}
};
/** The default preset of each page (used where a visitor's choice is not read). */
export const TONES = Object.fromEntries(Object.entries(PRESETS).map(([slug, set]) => [slug, set[DEFAULT_PRESET]]));
`;

const css = `/* ${banner} */
${slugs.map((slug) => {
  const base = presets[slug][DEFAULT_TONE];
  const others = TONE_PRESETS.filter((t) => t.id !== DEFAULT_TONE).map((t) => `html[data-series="${slug}"][data-tone="${t.id}"] {
  --series-bg: ${presets[slug][t.id].bg};
  --series-bg-alt: ${presets[slug][t.id].alt};
}`).join('\n');
  return `html[data-series="${slug}"] {
  --series-bg: ${base.bg};
  --series-bg-alt: ${base.alt};
  --series-fg: ${TONE_SETTINGS.ink};
  --series-muted: ${alpha(ink, 0.78)};
  --series-line: ${alpha(ink, 0.22)};
  --series-body: ${alpha(ink, 0.88)};
}
${others}`;
}).join('\n')}
`;

writeFileSync(new URL('tones.generated.js', OUT), js);
writeFileSync(new URL('tones.generated.css', OUT), css);
console.log('\nWrote src/themes/tones.generated.js and src/themes/tones.generated.css');
